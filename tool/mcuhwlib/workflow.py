"""Shared CMake configuration and the artifacts produced by a selected build.

Setup writes ordinary CMake presets for both the frontend and IDEs. Build records
describe actual outputs; flashing never guesses an image from a toolchain hash.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from mcuhwlib import environment, provenance
else:
    from . import environment, provenance

PRESET = "mcuhw"
PRESET_INCLUDE = ".mcuhw/CMakePresets.json"


def build_directory(project: Path, config: dict, state: dict) -> Path:
    tools = {name: value for name, value in state["tools"].items()
             if name in state.get("build_tools", [])}
    identity = json.dumps({"board": config["board"], "revision": config["revision"],
                           "startup": config["startup"], "tools": tools,
                           "frontend_python": state.get("frontend_python")}, sort_keys=True).encode()
    return project / "build" / (config["board"].replace("/", "-") + "-" + hashlib.sha256(identity).hexdigest()[:12])


def preset_document(project: Path, config: dict, root: Path, state: dict) -> dict:
    selected = state["build_tools"]
    tools = state["tools"]
    cache = {
        "MCUHW_SOURCE_DIR": str(root), "MCUHW_ROOT": str(root),
        "MCUHW_BOARD": config["board"], "MCUHW_BOARD_REVISION": config["revision"],
        "MCUHW_STARTUP": config["startup"],
        "MCUHW_EXAMPLE": config["example"],
        "CMAKE_MAKE_PROGRAM": tools["ninja"]["path"],
        "Python3_EXECUTABLE": state["frontend_python"]["path"],
        "MCUHW_ARTIFACT_POINTER": str(project / ".mcuhw/last-build.json"),
        "CMAKE_PROJECT_TOP_LEVEL_INCLUDES": str(project / ".mcuhw/verify-environment.cmake"),
    }
    cache.update(environment.cmake_variables(state, selected))
    return {"version": 6, "configurePresets": [{
        "name": PRESET, "displayName": f"mcuhw: {config['board']}@{config['revision']}",
        "generator": "Ninja", "binaryDir": str(build_directory(project, config, state)),
        "cmakeExecutable": tools['cmake']['path'],
        "toolchainFile": str(root / "cmake/McuhwToolchain.cmake"),
        "cacheVariables": cache, "environment": environment.preset_environment(state, selected),
    }], "buildPresets": [{"name": PRESET, "configurePreset": PRESET, "targets": ["firmware"]}]}


def install_presets(project: Path, config: dict, root: Path, state: dict) -> Path:
    """Merge only our include into user presets; preserve the user's own presets."""
    path = project / "CMakeUserPresets.json"
    document = {"version": 6}
    if path.exists():
        document = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(document, dict) or not isinstance(document.get("version"), int):
            raise environment.EnvironmentError(f"Invalid CMake user presets: {path}")
    for owner in (path, project / "CMakePresets.json"):
        if owner.exists():
            existing = json.loads(owner.read_text(encoding="utf-8"))
            for field in ("configurePresets", "buildPresets"):
                if any(item.get("name") == PRESET for item in existing.get(field, [])):
                    raise environment.EnvironmentError(f"{owner} already defines reserved preset {PRESET!r}; rename it before setup")
    document["version"] = max(6, document["version"])
    includes = document.setdefault("include", [])
    if PRESET_INCLUDE not in includes:
        includes.append(PRESET_INCLUDE)
    generated = preset_document(project, config, root, state)
    def literal(value):
        delimiter = '='
        while ']' + delimiter + ']' in str(value):
            delimiter += '='
        return '[' + delimiter + '[' + str(value) + ']' + delimiter + ']'
    # Plain CMake/IDE configuration enforces the same recorded installation as
    # the CLI. This hook belongs only to an explicitly set-up application.
    verify = ('# Generated by mcuhw setup.\ninclude_guard(GLOBAL)\n'
              'execute_process(COMMAND ' + literal(state['frontend_python']['path']) + ' ' +
              literal(root / 'tool/mcuhwlib/workflow.py') + ' verify --project ' + literal(project) +
              ' --cmake "${CMAKE_COMMAND}"' +
              '\n    RESULT_VARIABLE result OUTPUT_VARIABLE output ERROR_VARIABLE error)\n'
              'if(NOT result EQUAL 0)\n    message(FATAL_ERROR "${output}${error}")\nendif()\n')
    environment.write_json(project / PRESET_INCLUDE, generated)
    (project / '.mcuhw/verify-environment.cmake').write_text(verify, encoding='utf-8')
    environment.write_json(path, document)
    return Path(generated["configurePresets"][0]["binaryDir"])


def selected_preset(project: Path) -> dict:
    path = project / PRESET_INCLUDE
    if not path.is_file():
        raise environment.EnvironmentError("No shared CMake preset; run mcuhw.py setup --operation build")
    document = json.loads(path.read_text(encoding="utf-8"))
    return next(item for item in document["configurePresets"] if item["name"] == PRESET)


def record_build(build: Path, *, board: str, revision: str, startup: str, root: Path,
                 artifact: Path, sdk_build: Path | None = None, pointer: Path | None = None,
                 output: Path | None = None) -> Path:
    artifact = artifact.resolve()
    if not artifact.is_file():
        raise environment.EnvironmentError(f"Build did not produce its declared artifact: {artifact}")
    record = {"schema_version": 1, "board": board, "revision": revision, "startup": startup,
              "mcuhw_root": str(root.resolve()), "build_dir": str(build.resolve()),
              "artifacts": {"elf": str(artifact), "elf_sha256": environment.digest(artifact)}}
    if sdk_build is not None:
        record["artifacts"]["sdk_build"] = str(sdk_build.resolve())
        record["artifacts"]["flash_bundle_identity"] = provenance.flash_bundle(
            sdk_build, sdk_build / 'flasher_args.json')['identity']
    path = output.resolve() if output else build.resolve() / "mcuhw-build.json"
    environment.write_json(path, record)
    if pointer is not None:
        environment.write_json(pointer, {"schema_version": 1, "manifest": str(path)})
    return path


def load_build(project: Path, config: dict, build: str | None = None) -> dict:
    if build:
        path = Path(build).expanduser().resolve()
        if path.is_dir():
            default = path / "mcuhw-build.json"
            if default.is_file():
                path = default
            else:
                records = list(path.glob('*.build.json'))
                if len(records) != 1:
                    raise environment.EnvironmentError(f"Build directory {path} has {len(records)} artifact records; pass --build with the exact *.build.json file")
                path = records[0]
    else:
        pointer = project / ".mcuhw/last-build.json"
        if pointer.is_file():
            path = Path(environment.read_json(pointer)["manifest"])
        else:
            path = Path(selected_preset(project)["binaryDir"]) / "mcuhw-build.json"
    if not path.is_file():
        raise environment.EnvironmentError(f"No completed build record: {path}; build the mcuhw preset first, or pass --build PATH")
    record = environment.read_json(path)
    for field in ("board", "revision", "startup"):
        if record.get(field) != config[field]:
            raise environment.EnvironmentError(f"Build {field} {record.get(field)!r} differs from selected {config[field]!r}; select a matching completed build")
    artifact = Path(record["artifacts"]["elf"])
    if not artifact.is_file() or environment.digest(artifact) != record["artifacts"]["elf_sha256"]:
        raise environment.EnvironmentError(f"Recorded firmware is missing or changed: {artifact}; rebuild before flashing")
    if record['artifacts'].get('sdk_build'):
        sdk_build = Path(record['artifacts']['sdk_build'])
        actual = provenance.flash_bundle(sdk_build, sdk_build / 'flasher_args.json')['identity']
        if actual != record['artifacts'].get('flash_bundle_identity'):
            raise environment.EnvironmentError('Recorded SDK flash images or settings changed; rebuild before flashing')
    return record


def verify_environment(project: Path, cmake: Path | None = None) -> None:
    state = environment.read_json(project / '.mcuhw/environment.json')
    lock_path = project / '.mcuhw/toolchains.lock.json'
    if state.get('lock_sha256') != environment.digest(lock_path):
        raise environment.EnvironmentError('The project tool lock changed; run setup to update the shared CMake environment')
    if cmake is not None and cmake.resolve() != Path(state['tools']['cmake']['path']).resolve():
        raise environment.EnvironmentError(f"Use the configured CMake executable: {state['tools']['cmake']['path']}")
    interpreter = state.get('frontend_python', {})
    path = Path(interpreter.get('path', ''))
    if not path.is_file() or environment.digest(path) != interpreter.get('sha256'):
        raise environment.EnvironmentError('The recorded frontend Python changed; rerun setup')
    errors = environment.verify(state, environment.load_lock(lock_path), state['build_tools'])
    if errors:
        raise environment.EnvironmentError('\n'.join(errors))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="operation", required=True)
    record = sub.add_parser("record")
    for name in ("build", "root", "artifact"):
        record.add_argument("--" + name, type=Path, required=True)
    for name in ("board", "revision", "startup"):
        record.add_argument("--" + name, required=True)
    record.add_argument("--sdk-build", type=Path)
    record.add_argument("--pointer", type=Path)
    record.add_argument("--output", type=Path)
    verify = sub.add_parser('verify')
    verify.add_argument('--project', type=Path, required=True)
    verify.add_argument('--cmake', type=Path)
    args = parser.parse_args(argv)
    try:
        if args.operation == 'verify':
            verify_environment(args.project, args.cmake)
            return 0
        print(record_build(args.build, board=args.board, revision=args.revision, startup=args.startup,
                           root=args.root, artifact=args.artifact, sdk_build=args.sdk_build,
                           pointer=args.pointer, output=args.output))
        return 0
    except (ValueError, OSError, KeyError) as error:
        print(f"mcuhw build record: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
